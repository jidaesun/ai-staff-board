export function writePrompt(input: { instruction: string; analysis: string; topic: string; research: string }) {
  return `업무 지시:
${input.instruction}

업무 분석:
${input.analysis}

주제: ${input.topic}

자료 조사 메모:
${input.research}

위 내용으로 블로그 글을 써 주세요.`;
}

export function rewritePrompt(draft: string, issues: string[], research: string) {
  return `아래 블로그 글을 검토했더니 고칠 점이 있어요. 내용은 살리면서 아래 사항을 모두 고쳐 전체 글을 다시 써 주세요.
글쓰기 지침(말투, 용어, 구성, 규칙)도 다시 지켜 주세요.

고칠 점:
${issues.map((v) => `- ${v}`).join("\n")}

자료 조사 메모 (모델명과 가격은 여기 있는 것만 쓸 수 있어요):
${research || "(없음)"}

원래 글:
${draft}`;
}
